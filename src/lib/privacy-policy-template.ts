export const DEFAULT_PRIVACY_POLICY_CONTENT = `TURMINHA DA TATA
POLÍTICA DE PRIVACIDADE

1. OBJETIVO
Esta Política de Privacidade descreve como a Turminha da Tata trata os dados pessoais de responsáveis e crianças ao utilizar o Portal dos Pais e demais serviços da instituição, em conformidade com a Lei nº 13.709/2018 (Lei Geral de Proteção de Dados Pessoais — LGPD).

2. QUAIS DADOS COLETAMOS
Dados de identificação e contato do responsável e da criança; dados de saúde da criança quando fornecidos (alergias, restrições alimentares, medicamentos); fotografias, quando autorizadas separadamente por finalidade; registros da rotina diária (presença, alimentação, sono, higiene, atividades, humor); e dados de acesso ao sistema (login, dispositivo, data e hora de uso).

3. COMO USAMOS OS DADOS
Para prestar o serviço de cuidados infantis contratado, manter o responsável informado sobre o dia da criança através do Portal dos Pais, cumprir obrigações legais aplicáveis, e garantir a segurança da criança durante a permanência na instituição.

4. COM QUEM COMPARTILHAMOS
Não vendemos nem compartilhamos dados pessoais com terceiros para fins comerciais. Dados podem ser compartilhados com prestadores de serviço estritamente necessários à operação (ex.: armazenamento em nuvem, envio de notificações) e com autoridades quando exigido por lei.

5. SEGURANÇA DA INFORMAÇÃO
Adotamos medidas técnicas e administrativas para proteger os dados pessoais contra acessos não autorizados e situações de destruição, perda, alteração, comunicação ou difusão indevidas.

6. TEMPO DE GUARDA
Os dados são mantidos enquanto durar o vínculo da criança com a instituição, e pelo período adicional necessário para cumprir obrigações legais após o encerramento — ver a política de retenção detalhada em docs/lgpd.md.

7. DIREITOS DO TITULAR
O responsável pode, a qualquer momento, solicitar confirmação da existência de tratamento, acesso aos dados, correção de dados incompletos ou desatualizados, e demais direitos previstos no art. 18 da LGPD, através dos canais de contato informados pela administração.

8. ENCARREGADO DE DADOS (DPO)
O contato do encarregado de dados está disponível em docs/lgpd.md e nos canais oficiais da instituição.

9. ALTERAÇÕES DESTA POLÍTICA
Alterações relevantes nesta política geram uma nova versão, apresentada novamente ao responsável para leitura e assinatura — a versão anterior é preservada, nunca sobrescrita.

---

Este documento deverá ser revisado e aprovado pela administração da Turminha da Tata e, quando necessário, por profissional jurídico especializado em proteção de dados antes de sua utilização oficial.`;
